-- Variantes de producto (rubro ropa/calzado): un producto del catálogo
-- (products) puede tener varias combinaciones de talle y color, cada una con
-- su propio stock. Vive aparte de products para no tocar su esquema ni el flujo
-- actual del catálogo: los comercios que no usan variantes no cambian en nada.
--
-- Aislamiento por cuenta con RLS, igual que el resto. product_id referencia
-- products(id) (bigint) y cae en cascada si se borra el producto.
--
-- Correr una sola vez en el SQL Editor de Supabase (Dashboard > SQL Editor > New query).

create table if not exists public.producto_variantes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  talle text,
  color text,
  stock_actual numeric not null default 0,
  created_at timestamptz not null default now()
);

alter table public.producto_variantes enable row level security;

create policy "variantes_select_own" on public.producto_variantes
  for select using (auth.uid() = user_id);
create policy "variantes_insert_own" on public.producto_variantes
  for insert with check (auth.uid() = user_id);
create policy "variantes_update_own" on public.producto_variantes
  for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "variantes_delete_own" on public.producto_variantes
  for delete using (auth.uid() = user_id);

grant select, insert, update, delete on public.producto_variantes to authenticated;

create index if not exists variantes_user_id_idx on public.producto_variantes(user_id);
create index if not exists variantes_product_id_idx on public.producto_variantes(product_id);
